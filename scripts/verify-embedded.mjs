import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8');
const hub = read('hub/src/main.js');
const bridge = read('hub/src/buildEmbed.jsx');
const build = read('build/src/App.jsx');
const html = read('hub/index.html');
const deploy = read('scripts/deploy-build.mjs');
const redirects = JSON.parse(read('vercel.json')).rewrites;
assert.ok(hub.includes('root.hidden = buildActive') && hub.includes('switchVisibleApp(false)'));
assert.ok(hub.includes("import('./buildEmbed.jsx')"));
assert.ok(hub.includes("window.addEventListener('popstate'"));
assert.ok(hub.includes("'lac:navigate-hub'"));
assert.ok(bridge.includes("createRoot(appRoot).render(<BuildApp />)"));
assert.ok(bridge.includes("from '../../build/src/App.jsx'"));
assert.ok(bridge.includes("styles.css?inline"), 'BUILD CSS must not leak into HUB document');
assert.ok(build.includes('if (!/^\\/build(?:\\/|$)/.test(window.location.pathname)) return;'));
assert.ok(build.includes('lac:build-route-change'));
assert.ok(html.includes('lac-build-route'));
assert.ok(deploy.includes("'build/public'") && !deploy.includes("'build/dist'"));
assert.ok(redirects.length>=8 && redirects.every(r=>r.destination==='/index.html'));
assert.ok(existsSync(new URL('../hub/src/lib/productApi.js', import.meta.url)));
assert.ok(existsSync(new URL('../api/discord/callback.js', import.meta.url)));
console.log('PASS: embedded pilot keeps HUB DOM mounted, routes /build/* to one SPA, isolates BUILD CSS and retains existing server API.');
console.log('NOTE: compile and real browser login/history tests require Vercel deployment.');
