const hub=html({page:'hub'});
assert.doesNotMatch(hub,/data-action="browse-hub-contents"/,'Redundant content browsing buttons were retired');
assert.match(hub,/<button type="button" class="hub-feature hub-feature--interactive" data-action="open-company-console"/);
assert.match(hub,/<button type="button" class="hub-feature hub-feature--interactive" data-action="open-hub-game-info"/);
assert.equal((hub.match(/class="hub-feature hub-feature--interactive"/g)||[]).length,2,'Only connected services are actionable');
assert.equal((hub.match(/class="hub-feature hub-feature--pending"/g)||[]).length,2,'Unconnected services are not clickable');
assert.doesNotMatch(hub,/class="hub-feature__enter"[^>]*data-action/,'Arrow is not a separate control');
const standalone=html({page:'game-info'});
assert.match(standalone,/class="runtime-app runtime-app--game-info game-center"/);
assert.match(standalone,/class="axe-info"/,'Existing real game information UI reused');
assert.doesNotMatch(standalone,/선택 회사: LAC 회사/,'Standalone header is intentionally simplified; company-scoped data remains');
assert.match(standalone,/class="game-center__back" data-action="go-hub"/);
assert.match(standalone,/data-action="go-hub"/);
assert.doesNotMatch(standalone,/class="workspace-shell"|class="sidebar"|class="company-switcher"/,'Company management navigation must not leak into standalone game info');
const oldInfo=html({page:'info'});
assert.match(oldInfo,/class="workspace-shell"/,'Existing company game-info menu remains');
const noCompany=html({page:'game-info',companies:[],companyId:null});
assert.match(noCompany,/class="hub-home"/,'No company-scoped modbooks without company membership');
assert.doesNotMatch(noCompany,/class="game-center"/);
const stack={state:null, pushState(entry){this.state=entry;}};
recordPrimaryScreen(stack,'game-info');
assert.equal(readPrimaryScreen(stack.state),'game-info','Browser history recognizes standalone page');
const main=readFileSync(new URL('../src/main.js',import.meta.url),'utf8');
assert.match(main,/if\(action==='open-hub-game-info'\)[\s\S]*?navigatePrimaryScreen\('game-info'\)/);
assert.doesNotMatch(main,/browse-hub-contents|hub-contents--emphasized/);
assert.match(main,/\['info','game-info'\]\.includes\(state\.page\) && !state\.info\.loaded/);
console.log('PHASE 5 PASS: redundant browse action removed, native whole-card actions, pending cards inert, independent game shell, old info preserved, company scope, browser history.');
