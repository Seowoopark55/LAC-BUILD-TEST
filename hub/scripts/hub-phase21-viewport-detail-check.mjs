import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {renderHubHome} from '../src/ui/hubHome.js';
import {renderHubNewsStrip, renderHubBoard} from '../src/ui/hubBoard.js';
const hub=(r)=>readFileSync(new URL('../'+r,import.meta.url),'utf8');
const N=(id,title)=>({id,title,published_at:'2026-09-22T00:00:00Z'});
const B={hubBoard:{notices:[N('a','실제 공지 1'),N('b','실제 공지 2'),N('c','실제 공지 3'),N('d','실제 공지 4')],tickets:[],files:[],mode:'list',tab:'support',filterContent:'all',filterCategory:'all',filterStatus:'all',searchQuery:''},companies:[{id:'c1',name:'AXE'}],companyId:'c1',session:{user:{id:'u1',user_metadata:{name:'테스트'}}},platformAdmin:false,canCreateCompany:false};
const strip=renderHubNewsStrip(B);
assert.equal((strip.match(/data-notice-id=/g)||[]).length,3,'only three real announcements previewed');
assert.doesNotMatch(strip,/실제 공지 4/);
assert.match(strip,/서비스 문의<\/strong><small>/);
assert.match(strip,/게임 내 공식 공지와 별개인 LAC HUB 사이트 안내/);
const few=renderHubNewsStrip({...B,hubBoard:{...B.hubBoard,notices:[N('a','하나의 공지')]}});
assert.equal((few.match(/data-notice-id=/g)||[]).length,1);
assert.doesNotMatch(few,/실제 공지 2|가상 공지/);
const homepage=renderHubHome(B);
assert.match(homepage,/LAC 콘텐츠/);assert.match(homepage,/class="hub-news"/);
assert.equal((homepage.match(/class="hub-feature /g)||[]).length,4);
const t=(id,status)=>({id,status,content_key:'company',category:'question',title:'실제 문의',updated_at:'2026-09-22'});
const stats=renderHubBoard({...B,hubBoard:{...B.hubBoard,tickets:[t('a','pending'),t('b','pending'),t('c','complete')]}});
assert.match(stats,/<b>2<\/b><small>답변 대기/);assert.match(stats,/<b>0<\/b><small>확인 중/);assert.match(stats,/<b>1<\/b><small>처리 완료/);
assert.doesNotMatch(stats,/가상 문의|MoonRiver|Sunrise/);
const notices=renderHubBoard({...B,hubBoard:{...B.hubBoard,tab:'notices',notices:[N('n','한 개의 실제 공지')]}});
assert.match(notices,/hub-board__notice-info/);assert.doesNotMatch(notices,/hub-board__progress/);
assert.match(notices,/한 개의 실제 공지/);assert.doesNotMatch(notices,/PRIVATE SUPPORT/);
const compose=renderHubBoard({...B,hubBoard:{...B.hubBoard,mode:'compose'}});
assert.match(compose,/data-form="hub-board-ticket"/);assert.match(compose,/data-hub-board-images/);
assert.match(compose,/name="content_key"/);assert.match(compose,/name="category"/);
const css=hub('src/styles/hub-home.css')+'\n'+hub('src/styles/hub-board.css');
assert.match(css,/max-height:980px/);assert.match(css,/hub-board__notice-info/);
assert.match(css,/hub-news__items\{[^}]*overflow-y:auto/);
assert.doesNotMatch(hub('src/main.js'),/CREATE TABLE hub_tickets/i);
