import assert from 'node:assert/strict';
import {readFileSync, existsSync} from 'node:fs';
import {renderInfoPage} from '../src/ui/infoPage.js';
const src=new URL('../src/',import.meta.url);
const render=readFileSync(new URL('ui/render.js',src),'utf8');
const imports=readFileSync(new URL('styles.css',src),'utf8');
const css=readFileSync(new URL('styles/game-center-density.css',src),'utf8');
assert.equal(imports.match(/game-center-density\.css/g)?.length,1);
assert.ok(render.includes('renderInfoPage(state,{standalone:true})'));
assert.ok(render.includes("if (state.page === 'info') return renderInfoPage(state)"));
assert.ok(css.includes('.game-center .game-info-list-endcap'));
assert.ok(css.includes('.axe-info-detail:has(dl>div:nth-child(8))'));
for(const asset of ['hero','craft','production','quest','skill','modbook']) assert.ok(existsSync(new URL(`../public/hub/game-info/${asset}.webp`,src)));
const rows=Array.from({length:6},(_,i)=>({id:String(i+1),item_name:'실제테스트'+i,category:'PISTOL',success_rate:35,craft_rank:'B'}));
const state={info:{loaded:true,table:'info_crafts',data:{info_crafts:rows,info_craft_materials:[]},craftGroup:'총기류',filterPrimary:'피스톨',selectedId:'2'},companyId:'company-A',platformAdmin:false};
const independent=renderInfoPage(state,{standalone:true});
const embedded=renderInfoPage(state);
assert.ok(independent.includes('game-info-list-endcap'));
assert.ok(independent.includes('현재 분류 6건'));
assert.ok(independent.includes('실제테스트1'));
assert.ok(independent.includes('35'));
assert.ok(!embedded.includes('game-info-list-endcap'));
assert.equal((independent.match(/data-info-id=/g)||[]).length,6);
assert.ok(!independent.includes('수리 키트') && !independent.includes('금속 조각'));
const long={...state,info:{...state.info,data:{info_crafts:Array.from({length:9},(_,i)=>({...rows[0],id:String(i+1)}))}}};
assert.ok(!renderInfoPage(long,{standalone:true}).includes('game-info-list-endcap'));
console.log('PHASE 9 PASS: standalone-only short-list endcap uses actual filtered count, embedded UI unchanged, details use real records, long lists keep full height, category assets and responsive CSS available.');
